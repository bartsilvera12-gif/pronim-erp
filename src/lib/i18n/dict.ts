const dicts: Record<Lang, Dict> = { "es": es, "pt-BR": ptBR, "en": es };

export function translate(key: string, lang: Lang, vars?: Record<string, string | number>): string {
  const d = dicts[lang] ?? dicts.es;
  let raw = d[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      raw = raw.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return raw;
}

/**
 * Traducción SIN hook, para usar en cualquier lado.
 *
 * `useT()` necesita estar dentro de un componente con el provider arriba, y
 * hay cientos de textos repartidos en helpers, callbacks y componentes sueltos
 * donde agregar el hook es invasivo. Esta versión lee el idioma del registro
 * global que publica el I18nProvider (el mismo que usa `fmtActive` para la
 * moneda), así que basta con importarla y envolver el texto.
 */
export function tt(key: string, vars?: Record<string, string | number>): string {
  return translate(key, getActiveLang(), vars);
}
